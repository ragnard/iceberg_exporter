// Package rules embeds the table health Prometheus rules and renders them as
// a plain rules file or as a Prometheus Operator PrometheusRule.
//
// iceberg_exporter.rules.yml is the single source of truth; the
// PrometheusRule is derived from it at runtime, so the two cannot drift.
package rules

import (
	"bytes"
	_ "embed"
	"fmt"
	"sort"

	"gopkg.in/yaml.v3"
)

// Prometheus is the canonical rules file, loadable via rule_files.
//
//go:embed iceberg_exporter.rules.yml
var Prometheus []byte

// DefaultName is the default metadata.name of the PrometheusRule.
const DefaultName = "iceberg-exporter"

// Options customise the PrometheusRule metadata.
type Options struct {
	Name      string            // defaults to DefaultName
	Namespace string            // omitted when empty
	Labels    map[string]string // added to app.kubernetes.io/name; may override it
}

// PrometheusRule renders the embedded rules as a monitoring.coreos.com/v1
// PrometheusRule.
func PrometheusRule(opts Options) ([]byte, error) {
	return prometheusRule(Prometheus, opts)
}

// prometheusRule wraps a rules file (a top-level `groups` list) as the spec
// of a PrometheusRule. Comments inside the groups are preserved; the source
// file's header comment is dropped.
func prometheusRule(canonical []byte, opts Options) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(canonical, &doc); err != nil {
		return nil, fmt.Errorf("parse rules: %w", err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("parse rules: expected a mapping document")
	}
	spec := doc.Content[0]
	if len(spec.Content) != 2 || spec.Content[0].Value != "groups" {
		return nil, fmt.Errorf("parse rules: expected exactly one top-level key, groups")
	}
	spec.HeadComment = ""
	spec.Content[0].HeadComment = ""

	name := opts.Name
	if name == "" {
		name = DefaultName
	}
	labels := map[string]string{"app.kubernetes.io/name": "iceberg-exporter"}
	for k, v := range opts.Labels {
		labels[k] = v
	}
	keys := make([]string, 0, len(labels))
	for k := range labels {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	labelNode := mapping()
	for _, k := range keys {
		labelNode.Content = append(labelNode.Content, scalar(k), scalar(labels[k]))
	}

	metadata := mapping("name", scalar(name))
	if opts.Namespace != "" {
		metadata.Content = append(metadata.Content, scalar("namespace"), scalar(opts.Namespace))
	}
	metadata.Content = append(metadata.Content, scalar("labels"), labelNode)

	out := mapping(
		"apiVersion", scalar("monitoring.coreos.com/v1"),
		"kind", scalar("PrometheusRule"),
		"metadata", metadata,
		"spec", spec,
	)

	var buf bytes.Buffer
	buf.WriteString("# Generated by `iceberg_exporter rules -format prometheusrule`.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(out); err != nil {
		return nil, fmt.Errorf("encode PrometheusRule: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("encode PrometheusRule: %w", err)
	}
	return buf.Bytes(), nil
}

func scalar(v string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
}

func mapping(kv ...any) *yaml.Node {
	n := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	for i := 0; i < len(kv); i += 2 {
		n.Content = append(n.Content, scalar(kv[i].(string)), kv[i+1].(*yaml.Node))
	}
	return n
}
